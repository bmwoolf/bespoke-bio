#!/usr/bin/env python3
"""Read standard Boltz fixed-candidate results; confidence is not affinity.

Expected manifest is generated by prepare_candidate_validation.py. Explicit
chain IDs are verified against exact sequences before interpreting numeric chain
indices. Oligomer target-target scores are never used as binder scores.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from collections import defaultdict
from pathlib import Path

import gemmi
import numpy as np


def stats(values):
    values = [float(v) for v in values if v is not None and np.isfinite(v)]
    return {'n': len(values), 'mean': float(np.mean(values)) if values else None,
            'min': min(values) if values else None, 'max': max(values) if values else None}


def read_chains(path, expected):
    structure = gemmi.read_structure(str(path))
    if len(structure) != 1:
        raise ValueError('Expected one predicted model')
    chains = {}
    for chain in structure[0]:
        residues = [r for r in chain if gemmi.find_tabulated_residue(r.name).is_amino_acid()]
        sequence = ''.join(gemmi.find_tabulated_residue(r.name).one_letter_code for r in residues)
        if chain.name not in expected or sequence != expected[chain.name]:
            raise ValueError(f'Predicted chain {chain.name} sequence differs from manifest')
        if chain.name in chains:
            raise ValueError('Duplicate chain name')
        ca = [r.find_atom('CA', '*') for r in residues]
        if any(a is None for a in ca):
            raise ValueError('Predicted residue missing CA')
        confidence = np.array([a.b_iso for a in ca])
        if np.any((confidence < 0) | (confidence > 100)):
            raise ValueError('Standard Boltz CIF pLDDT outside 0–100')
        chains[chain.name] = {'residues': residues, 'plddt_0_100': confidence}
    if set(chains) != set(expected):
        raise ValueError('Missing predicted chain')
    return chains


def contact_mask(left, right, cutoff=5.0, strict=False):
    """Residue heavy-atom contacts, arbitrary descriptive cutoff in angstroms."""
    result = np.zeros((len(left), len(right)), dtype=bool)
    for i, residue in enumerate(left):
        a = np.array([[atom.pos.x, atom.pos.y, atom.pos.z] for atom in residue
                      if not atom.element.is_hydrogen and atom.occ > 0])
        for j, other in enumerate(right):
            b = np.array([[atom.pos.x, atom.pos.y, atom.pos.z] for atom in other
                          if not atom.element.is_hydrogen and atom.occ > 0])
            if len(a) and len(b):
                distance2 = np.sum((a[:, None] - b[None, :]) ** 2, axis=-1)
                result[i, j] = bool(np.any(distance2 < cutoff**2 if strict else distance2 <= cutoff**2))
    return result


def assembly_alignment(mobile_by_chain, reference_by_chain):
    """One proper rigid fit of all matched target CAs; do not fit subunits away."""
    names = list(reference_by_chain)
    if set(names) != set(mobile_by_chain):
        raise ValueError('Assembly chain sets differ')
    mobile = np.concatenate([np.asarray(mobile_by_chain[n], dtype=float) for n in names])
    reference = np.concatenate([np.asarray(reference_by_chain[n], dtype=float) for n in names])
    if mobile.shape != reference.shape or mobile.shape[1:] != (3,) or len(mobile) < 3:
        raise ValueError('Assembly fit needs at least three matched CA positions')
    if not np.isfinite(mobile).all() or not np.isfinite(reference).all():
        raise ValueError('Nonfinite assembly coordinates')
    center_m, center_r = mobile.mean(axis=0), reference.mean(axis=0)
    u, _, vt = np.linalg.svd((mobile - center_m).T @ (reference - center_r))
    correction = np.eye(3)
    correction[-1, -1] = np.linalg.det(u @ vt)
    rotation = u @ correction @ vt
    aligned = (mobile - center_m) @ rotation + center_r
    distances2 = np.sum((aligned - reference)**2, axis=1)
    per_chain, offset = {}, 0
    for name in names:
        count = len(reference_by_chain[name])
        per_chain[name] = {'matched_CA': count,
                           'CA_RMSD_after_global_fit_A': float(np.sqrt(distances2[offset:offset + count].mean()))}
        offset += count
    return {'global_CA_RMSD_A': float(np.sqrt(distances2.mean())),
            'matched_CA': len(mobile), 'per_chain': per_chain,
            'mapping_policy': 'Fixed declared chain IDs and audited input positions; no symmetry permutation optimization.'}


def target_assembly_integrity(chains, row, root):
    if not row['target_chains'] or row.get('target_template') is False:
        return {'status': 'not_applicable', 'reason': 'No target template supplied for this prediction'}
    try:
        schema = json.loads((root / row['input']).read_text())
        entries = schema.get('templates', [])
        if len(entries) != 1 or not row.get('observed_template_positions'):
            raise ValueError('Single template with audited observed-position mapping unavailable')
        template_path = root / entries[0]['cif']
        if not template_path.exists():
            raise ValueError('Experimental target template unavailable')
        structure = gemmi.read_structure(str(template_path))
        if len(structure) != 1:
            raise ValueError('Reference must contain one predetermined model')
        mobile, reference = {}, {}
        for spec in row['target_chains']:
            name, sequence = spec['chain'], spec['sequence']
            if name not in {chain.name for chain in structure[0]}:
                raise ValueError('Reference chain missing')
            reference_residues = list(structure[0][name])
            positions = row['observed_template_positions'][name]
            if [r.seqid.num for r in reference_residues] != positions:
                raise ValueError('Reference positions differ from audited map')
            ref_ca, pred_ca = [], []
            for residue, position in zip(reference_residues, positions):
                if gemmi.find_tabulated_residue(residue.name).one_letter_code != sequence[position - 1]:
                    raise ValueError('Reference residue differs from exact target sequence')
                atom = residue.find_atom('CA', '*')
                if atom is None:
                    raise ValueError('Audited reference position has no CA')
                predicted = chains[name]['residues'][position - 1].find_atom('CA', '*')
                ref_ca.append([atom.pos.x, atom.pos.y, atom.pos.z])
                pred_ca.append([predicted.pos.x, predicted.pos.y, predicted.pos.z])
            reference[name], mobile[name] = ref_ca, pred_ca
        return {'status': 'assessed', 'reference': entries[0]['cif'],
                **assembly_alignment(mobile, reference)}
    except (ValueError, KeyError, IndexError, RuntimeError) as exc:
        return {'status': 'unavailable', 'reason': str(exc)}


def aligned_pose_metrics(predicted_target, reference_target, predicted_binder, reference_binder):
    """Target-fit binder displacement versus binder-only fold deviation, in Å."""
    pt, rt, pb, rb = [np.asarray(x, dtype=float) for x in
                      (predicted_target, reference_target, predicted_binder, reference_binder)]
    if pt.shape != rt.shape or pb.shape != rb.shape or min(len(pt), len(pb)) < 3:
        raise ValueError('Exact matched target and binder CAs required for pose assessment')
    if any(x.ndim != 2 or x.shape[1] != 3 or not np.isfinite(x).all() for x in (pt, rt, pb, rb)):
        raise ValueError('Invalid pose coordinates')
    pc, rc = pt.mean(axis=0), rt.mean(axis=0)
    u, _, vt = np.linalg.svd((pt - pc).T @ (rt - rc))
    correction = np.eye(3)
    correction[-1, -1] = np.linalg.det(u @ vt)
    rotation = u @ correction @ vt
    aligned_target = (pt - pc) @ rotation + rc
    aligned_binder = (pb - pc) @ rotation + rc
    own_fold = assembly_alignment({'binder': pb}, {'binder': rb})['global_CA_RMSD_A']
    return {'target_CA_RMSD_A': float(np.sqrt(np.mean(np.sum((aligned_target - rt)**2, axis=1)))),
            'binder_CA_RMSD_after_target_alignment_A': float(np.sqrt(np.mean(np.sum((aligned_binder - rb)**2, axis=1)))),
            'binder_centroid_displacement_after_target_alignment_A': float(np.linalg.norm(aligned_binder.mean(axis=0) - rb.mean(axis=0))),
            'binder_own_fold_CA_RMSD_A': own_fold, 'target_matched_CA': len(pt), 'binder_matched_CA': len(pb)}


def contact_recovery(predicted_target, predicted_binder, reference_target, reference_binder, cutoff=5.0):
    """Exact sequence-position residue contacts at strict heavy-atom distance < cutoff.

    Interface CA RMSD jointly aligns the reference-contact target and binder
    residues, using the identical residue sets in prediction and reference.
    This is a custom CA-only interface metric, not DockQ.
    """
    for predicted, reference in ((predicted_target, reference_target), (predicted_binder, reference_binder)):
        pseq = ''.join(gemmi.find_tabulated_residue(r.name).one_letter_code for r in predicted)
        rseq = ''.join(gemmi.find_tabulated_residue(r.name).one_letter_code for r in reference)
        if pseq != rseq:
            raise ValueError('Contact recovery requires exact full sequence-position mapping')
    native = contact_mask(reference_binder, reference_target, cutoff, strict=True)
    predicted = contact_mask(predicted_binder, predicted_target, cutoff, strict=True)
    shared = int(np.logical_and(native, predicted).sum())
    native_count, predicted_count = int(native.sum()), int(predicted.sum())
    union = int(np.logical_or(native, predicted).sum())
    binder_positions = np.where(np.any(native, axis=1))[0]
    target_positions = np.where(np.any(native, axis=0))[0]
    mobile, reference = [], []
    for positions, pred_res, ref_res in ((target_positions, predicted_target, reference_target),
                                         (binder_positions, predicted_binder, reference_binder)):
        for index in positions:
            a, b = pred_res[index].find_atom('CA', '*'), ref_res[index].find_atom('CA', '*')
            if a is None or b is None:
                raise ValueError('Contact-interface residue missing CA')
            mobile.append([a.pos.x, a.pos.y, a.pos.z])
            reference.append([b.pos.x, b.pos.y, b.pos.z])
    rmsd = None
    if len(mobile) >= 3:
        rmsd = assembly_alignment({'interface': mobile}, {'interface': reference})['global_CA_RMSD_A']
    return {'heavy_atom_contact_rule': f'strict distance < {cutoff:g} angstroms; occupied non-hydrogen atoms',
            'reference_residue_contacts': native_count, 'predicted_residue_contacts': predicted_count,
            'recovered_residue_contacts': shared,
            'contact_recall': shared / native_count if native_count else None,
            'contact_precision': shared / predicted_count if predicted_count else None,
            'contact_jaccard': shared / union if union else None,
            'reference_target_interface_positions_1based': (target_positions + 1).tolist(),
            'reference_binder_interface_positions_1based': (binder_positions + 1).tolist(),
            'reference_interface_CA_jointfit_RMSD_A': rmsd,
            'interface_CA_count': len(mobile),
            'interface_metric_definition': 'Proper rigid joint fit of CAs from reference-contact residues in BOTH chains, exact sequence positions; not DockQ or a full-backbone iRMSD.'}


def safe_evaluation_reference(root, relative, expected_sha256=None):
    if root is None or Path(relative).is_absolute():
        raise ValueError('Evaluation-only reference must be root-relative')
    root = Path(root).resolve()
    path = (root / relative).resolve()
    if not path.is_relative_to(root) or not path.is_file():
        raise ValueError('Evaluation-only reference must remain contained in prepared output')
    if expected_sha256 and hashlib.sha256(path.read_bytes()).hexdigest() != expected_sha256:
        raise ValueError('Evaluation-only reference SHA256 mismatch')
    return path


def posthoc_target_references(chains, row, root):
    """Experimental comparisons done AFTER prediction; never template conditioning."""
    specifications = row.get('target_analysis_references_EVALUATION_ONLY', [])
    if not row.get('target_chains'):
        return {'status': 'not_applicable', 'references': []}
    if not specifications:
        return {'status': 'not_provided', 'references': []}
    results = []
    for spec in specifications:
        result = {'role': spec['role'], 'pdb_id': spec.get('pdb_id'),
                  'conditioning': 'Evaluation-only coordinates; not supplied to predictor'}
        try:
            path = safe_evaluation_reference(root, spec['path'], spec.get('sha256'))
            reference = gemmi.read_structure(str(path))
            if len(reference) != 1:
                raise ValueError('Posthoc reference must have one model')
            name = spec.get('prediction_chain', 'A')
            sequence = next(c['sequence'] for c in row['target_chains'] if c['chain'] == name)
            residues = list(reference[0][spec.get('reference_chain', 'A')])
            positions = spec['input_positions']
            if [r.seqid.num for r in residues] != positions or len(set(positions)) != len(positions):
                raise ValueError('Posthoc coordinates differ from audited input-position mapping')
            mobile, destination = [], []
            for residue, position in zip(residues, positions):
                if not 1 <= position <= len(sequence) or gemmi.find_tabulated_residue(residue.name).one_letter_code != sequence[position-1]:
                    raise ValueError('Posthoc reference target sequence mismatch')
                predicted = chains[name]['residues'][position-1]
                if predicted.seqid.num != position:
                    raise ValueError('Prediction input-position numbering mismatch')
                left, right = predicted.find_atom('CA', '*'), residue.find_atom('CA', '*')
                if left is None or right is None:
                    raise ValueError('Posthoc target comparison missing CA')
                mobile.append([left.pos.x, left.pos.y, left.pos.z])
                destination.append([right.pos.x, right.pos.y, right.pos.z])
            metrics = assembly_alignment({name: mobile}, {name: destination})
            result.update(status='assessed', reference=str(path),
                          target_input_coverage=len(positions)/len(sequence), **metrics)
        except (ValueError, KeyError, IndexError, RuntimeError, OSError, StopIteration) as exc:
            result.update(status='unavailable', reason=str(exc))
        results.append(result)
    return {'status': 'evaluated', 'references': results}


def reference_pose(chains, row, evaluation, root=None):
    explicit = row.get('source_design_complex_pose_EVALUATION_ONLY')
    if row.get('kind') == 'binder_alone' and not explicit:
        return {'status': 'not_applicable', 'reason': 'No target to anchor binder pose'}
    if row.get('kind') == 'putative_negative':
        return {'status': 'not_applicable', 'reason': 'Shuffled sequence has no experimental reference pose'}
    if not evaluation and not explicit:
        return {'status': 'unavailable', 'reason': 'Evaluation-only reference manifest unavailable'}
    try:
        if explicit:
            reference = safe_evaluation_reference(root, explicit, row.get('source_design_complex_pose_sha256'))
            interpretation = 'Agreement with original computational design pose, NOT accuracy or experimental validation.'
        elif row['kind'] == 'experimental_positive':
            reference = evaluation['positive_control']['experimental_complex_EVALUATION_ONLY']
            interpretation = 'Experimental complex pose agreement; reference binder coordinates were not input.'
        else:
            candidates = [c for c in evaluation['fixed_candidates'] if c['candidate_id'] == row['candidate_id']]
            if len(candidates) != 1:
                raise ValueError('Unique original candidate complex unavailable')
            reference = candidates[0]['prior_complex_for_evaluation_only']
            interpretation = 'Agreement with original computational design pose, NOT accuracy or experimental validation.'
        structure = gemmi.read_structure(str(reference))
        if len(structure) != 1:
            raise ValueError('Reference must have one model')
        binder_sequence = row['binder_sequence']
        reference_chains = []
        for chain in structure[0]:
            residues = [r for r in chain if gemmi.find_tabulated_residue(r.name).is_amino_acid()]
            sequence = ''.join(gemmi.find_tabulated_residue(r.name).one_letter_code for r in residues)
            reference_chains.append((chain.name, sequence, residues))
        if row.get('kind') == 'binder_alone':
            matches = [(name, residues) for name, seq, residues in reference_chains if seq == binder_sequence]
            if len(matches) != 1:
                raise ValueError('Unique original binder sequence unavailable')
            def own_coords(residues):
                atoms = [r.find_atom('CA', '*') for r in residues]
                if any(a is None for a in atoms):
                    raise ValueError('Missing CA in binder fold reference')
                return [[a.pos.x, a.pos.y, a.pos.z] for a in atoms]
            own = assembly_alignment({'binder': own_coords(chains[row['binder_chain']]['residues'])},
                                     {'binder': own_coords(matches[0][1])})['global_CA_RMSD_A']
            return {'status': 'assessed', 'reference': str(reference),
                    'interpretation': 'Binder-only fold agreement with original computational design binder; NOT experimental accuracy.',
                    'pose_status': 'not_applicable: binder alone has no target anchor',
                    'binder_own_fold_CA_RMSD_A': own}
        anchor = row['target_chains'][0]['chain']
        target_sequence = row['target_chains'][0]['sequence']
        matches = []
        for sequence in (target_sequence, binder_sequence):
            matching = [(name, residues) for name, seq, residues in reference_chains if seq == sequence]
            if len(matching) != 1:
                raise ValueError('Reference target/binder sequence match is missing or ambiguous')
            matches.append(matching[0])
        if matches[0][0] == matches[1][0]:
            raise ValueError('Reference target and binder map to same chain')
        def coords(residues):
            atoms = [r.find_atom('CA', '*') for r in residues]
            if any(a is None for a in atoms):
                raise ValueError('Reference/prediction missing CA; exact full-sequence mapping required')
            return [[a.pos.x, a.pos.y, a.pos.z] for a in atoms]
        metrics = aligned_pose_metrics(coords(chains[anchor]['residues']), coords(matches[0][1]),
                                       coords(chains[row['binder_chain']]['residues']), coords(matches[1][1]))
        return {'status': 'assessed', 'reference': str(reference), 'interpretation': interpretation,
                'predicted_target_anchor': anchor, 'reference_target_chain': matches[0][0],
                'reference_binder_chain': matches[1][0],
                'homomer_caveat': 'First declared target chain is the fixed anchor; no equivalent-subunit remapping.',
                'reference_contact_recovery': contact_recovery(chains[anchor]['residues'],
                    chains[row['binder_chain']]['residues'], matches[0][1], matches[1][1]),
                'target_anchor_CA_RMSD_A': metrics['target_CA_RMSD_A'],
                **metrics}
    except (ValueError, KeyError, IndexError, RuntimeError, OSError) as exc:
        return {'status': 'unavailable', 'reason': str(exc)}


def heavy_atom_overlap(left, right, cutoff=2.0):
    """Severe overlap screen only; no force field or clash repair."""
    def atoms(residues):
        coords, owners = [], []
        for index, residue in enumerate(residues):
            for atom in residue:
                if not atom.element.is_hydrogen and atom.occ > 0:
                    coords.append([atom.pos.x, atom.pos.y, atom.pos.z])
                    owners.append(index)
        return np.asarray(coords), np.asarray(owners)
    a, a_owner = atoms(left)
    b, b_owner = atoms(right)
    if not len(a) or not len(b):
        return {'status': 'unavailable', 'reason': 'No occupied heavy atoms'}
    count, minimum = 0, float('inf')
    left_res, right_res = set(), set()
    for start in range(0, len(a), 128):
        distances2 = np.sum((a[start:start + 128, None] - b[None, :])**2, axis=-1)
        minimum = min(minimum, float(distances2.min()))
        i, j = np.where(distances2 < cutoff**2)
        count += len(i)
        left_res.update(a_owner[start + i].tolist())
        right_res.update(b_owner[j].tolist())
    return {'status': 'assessed', 'strict_cutoff_A': cutoff, 'atom_pairs_below_cutoff': count,
            'binder_residues_below_cutoff': len(left_res), 'target_residues_below_cutoff': len(right_res),
            'minimum_heavy_atom_distance_A': float(np.sqrt(minimum))}


def pair_scores(confidence, chain_order, binder):
    numeric = {name: str(i) for i, name in enumerate(chain_order)}
    raw = confidence.get('pair_chains_iptm', {})
    binder_pairs, target_pairs = {}, {}
    for left in chain_order:
        for right in chain_order:
            if left == right:
                continue
            value = raw.get(numeric[left], {}).get(numeric[right])
            destination = binder_pairs if binder in (left, right) else target_pairs
            destination[f'{left}|{right}'] = value
    return binder_pairs, target_pairs


def analyze_case(root, row, command, evaluation=None):
    base = root / command['expected_prediction_directory'] / row['id']
    paths = {'structure': base / f"{row['id']}_model_0.cif",
             'confidence': base / f"confidence_{row['id']}_model_0.json",
             'pae': base / f"pae_{row['id']}_model_0.npz",
             'plddt': base / f"plddt_{row['id']}_model_0.npz"}
    result = {k: row.get(k) for k in ('id', 'target_id', 'candidate_id', 'kind', 'context',
                                      'source_native_filter', 'binder_chain')}
    result.update({'seed': command['seed'], 'files': {k: str(v.relative_to(root)) for k, v in paths.items()},
                   'status': 'missing', 'missing_files': [k for k, v in paths.items() if not v.exists()]})
    if result['missing_files']:
        return result
    expected = {c['chain']: c['sequence'] for c in row['target_chains']}
    expected[row['binder_chain']] = row['binder_sequence']
    try:
        chains = read_chains(paths['structure'], expected)
        # Standard schema preserves chain insertion order; verify written order too.
        if list(chains) != list(expected):
            raise ValueError('CIF chain ordering differs from native input; numeric confidence mapping unavailable')
        confidence = json.loads(paths['confidence'].read_text())
        plddt = np.load(paths['plddt'], allow_pickle=False)['plddt'].reshape(-1)
        pae = np.load(paths['pae'], allow_pickle=False)['pae']
        size = sum(len(v) for v in expected.values())
        if plddt.shape != (size,) or pae.shape != (size, size):
            raise ValueError('Confidence array dimensions differ from exact protein sequence lengths')
        if np.any((plddt < 0) | (plddt > 1)):
            raise ValueError('Native pLDDT NPZ is expected on 0–1 scale')
        cif_plddt = np.concatenate([c['plddt_0_100'] for c in chains.values()])
        if not np.allclose(plddt * 100, cif_plddt, atol=.06):
            raise ValueError('CIF/NPZ pLDDT scales or residue order disagree')
        slices, offset = {}, 0
        for name, sequence in expected.items():
            slices[name] = slice(offset, offset + len(sequence))
            offset += len(sequence)
        binder = row['binder_chain']
        binder_pairs, target_pairs = pair_scores(confidence, list(chains), binder)
        result.update({'status': 'analyzed', 'chain_plddt_0_100': {
            name: stats(plddt[sl] * 100) for name, sl in slices.items()},
            'binder_plddt_0_100': stats(plddt[slices[binder]] * 100),
            'binder_target_chainpair_iptm': binder_pairs, 'target_target_chainpair_iptm': target_pairs,
            'overall_complex_iptm_context_only': confidence.get('iptm'),
            'overall_ptm': confidence.get('ptm'), 'binder_target_interfaces': {},
            'target_assembly_integrity': target_assembly_integrity(chains, row, root),
            'binder_reference_pose': reference_pose(chains, row, evaluation, root),
            'posthoc_target_reference_geometry': posthoc_target_references(chains, row, root)})
        for target in expected:
            if target == binder:
                continue
            contacts = contact_mask(chains[binder]['residues'], chains[target]['residues'])
            block = pae[slices[binder], slices[target]]
            reverse = pae[slices[target], slices[binder]].T
            interface_binder = np.any(contacts, axis=1)
            result['binder_target_interfaces'][target] = {
                'severe_heavy_atom_overlap': heavy_atom_overlap(chains[binder]['residues'], chains[target]['residues']),
                'contact_cutoff_A': 5, 'residue_contact_pairs': int(contacts.sum()),
                'binder_contact_residues': int(interface_binder.sum()),
                'target_contact_residues': int(np.any(contacts, axis=0).sum()),
                'binder_interface_plddt_0_100': stats(plddt[slices[binder]][interface_binder] * 100),
                'pae_binder_rows_target_columns_A': stats(block.flatten()),
                'pae_target_rows_binder_columns_A': stats(reverse.flatten()),
                'contact_pae_binder_rows_target_columns_A': stats(block[contacts]),
                'contact_pae_target_rows_binder_columns_A': stats(reverse[contacts])}
    except (ValueError, KeyError, IndexError, RuntimeError) as exc:
        result.update(status='unavailable', error=str(exc))
    return result


def analyze(root, evaluation_path=None):
    root = Path(root).resolve()
    manifest = json.loads((root / 'manifest.json').read_text())
    evaluation_path = Path(evaluation_path) if evaluation_path else root.parent / 'candidates/manifest.json'
    evaluation = json.loads(evaluation_path.read_text()) if evaluation_path.exists() else None
    rows = [analyze_case(root, row, command, evaluation) for command in manifest['commands']
            for row in manifest['inputs'] if row['condition'] == command['condition']]
    grouped = defaultdict(list)
    for row in rows:
        if row['status'] == 'analyzed':
            grouped[row['id']].append(row)
    summary = []
    for case in manifest['inputs']:
        selected = grouped[case['id']]
        pairkeys = sorted({k for r in selected for k in r['binder_target_chainpair_iptm']})
        summary.append({'id': case['id'], 'kind': case['kind'], 'context': case['context'],
                        'source_native_filter': case['source_native_filter'],
                        'completed': len(selected), 'expected': len(manifest['seeds']),
                        'binder_plddt_0_100': stats(r['binder_plddt_0_100']['mean'] for r in selected),
                        'binder_CA_RMSD_after_target_alignment_A': stats(r.get('binder_reference_pose', {}).get('binder_CA_RMSD_after_target_alignment_A') for r in selected),
                        'binder_own_fold_CA_RMSD_A': stats(r.get('binder_reference_pose', {}).get('binder_own_fold_CA_RMSD_A') for r in selected),
                        'target_global_CA_RMSD_A': stats(r.get('target_assembly_integrity', {}).get('global_CA_RMSD_A') for r in selected),
                        'target_anchor_design_CA_RMSD_A': stats(r.get('binder_reference_pose', {}).get('target_anchor_CA_RMSD_A') for r in selected),
                        'posthoc_target_heldout_CA_RMSD_A': stats(ref.get('global_CA_RMSD_A')
                            for r in selected for ref in r.get('posthoc_target_reference_geometry', {}).get('references', [])
                            if ref.get('role') == 'held_out' and ref.get('status') == 'assessed'),
                        'binder_target_atom_pairs_lt2A': stats(sum(i['severe_heavy_atom_overlap'].get('atom_pairs_below_cutoff', 0)
                            for i in r['binder_target_interfaces'].values()) for r in selected if r['binder_target_interfaces']),
                        'binder_target_chainpair_iptm': {k: stats(r['binder_target_chainpair_iptm'].get(k)
                                                                 for r in selected) for k in pairkeys}})
    # Seed-matched positive/decoy differences describe this sanity check only.
    paired_control_deltas = []
    for seed in manifest['seeds']:
        positives = [r for r in rows if r['seed'] == seed and r['kind'] == 'experimental_positive'
                     and r['status'] == 'analyzed']
        negatives = [r for r in rows if r['seed'] == seed and r['kind'] == 'putative_negative'
                     and r['status'] == 'analyzed']
        if len(positives) == len(negatives) == 1:
            pos, neg = positives[0], negatives[0]
            paired_control_deltas.append({'seed': seed, 'positive_minus_decoy_chainpair_iptm': {
                k: float(v - neg['binder_target_chainpair_iptm'][k])
                for k, v in pos['binder_target_chainpair_iptm'].items()
                if v is not None and neg['binder_target_chainpair_iptm'].get(k) is not None}})
    return {'expected_predictions': len(rows), 'analyzed_predictions': sum(r['status'] == 'analyzed' for r in rows),
            'cases': rows, 'summary': summary, 'matched_positive_decoy_deltas': paired_control_deltas,
            'limitations': manifest['limitations'] + [
                'Chainpair ipTM keys retain native outer|inner order. Native computation averages over outer-chain tokens and maximizes over inner-chain anchor tokens.',
                'Native chainpair TM length scaling uses the whole complex; monomer/oligomer scores are not directly calibrated across different total lengths.',
                'Overall complex ipTM is context only; target-target interfaces can dominate oligomers.',
                'pLDDT reported on 0–100 scale; native NPZ 0–1 values cross-checked against CIF B factors.',
                'PAE is in angstroms; row/column directions reported explicitly without symmetrization.',
                'Contacts use an arbitrary <=5 angstrom heavy-atom cutoff; absence of contacts yields unavailable contact-local confidence.',
                'Assembly RMSD uses one global fit across all target subunits at audited observed CA positions. Per-chain RMSDs use that same fit, so subunit rearrangements are retained.',
                'Assembly mapping uses declared chain IDs; equivalent homooligomer chain permutations may increase RMSD and require inspection.',
                'Severe overlap is a geometric screen using occupied heavy-atom pairs <2 angstroms; no force-field or biological compatibility validation.',
                'Positive-control binder pose is compared with experimental 1WQJ after aligning only the target. Designed binders compare to their original computational poses as agreement, NOT accuracy.',
                'Reference pose assessment requires exact unique full target and binder sequences and CA coverage. Homomers use first declared target chain as fixed anchor.',
                'No new pass/fail threshold assigned. Original native design filter is historical provenance only.']}


def render(report, output):
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    (output / 'analysis.json').write_text(json.dumps(report, indent=2) + '\n')
    lines = ['# Fixed-binder standard Boltz reevaluation', '',
             f"Analyzed {report['analyzed_predictions']}/{report['expected_predictions']} predictions.", '',
             'Target-conditioned complexes; scores describe model confidence, not binding affinity.', '',
             '| Case | Original filter | Results | Binder pLDDT (0–100) | Binder–target chainpair ipTM mean [range] | Target global RMSD Å | Binder–target atom pairs <2Å | Binder pose RMSD Å after target fit |',
             '|---|---|---|---|---|---|---|---|']
    def fmt(stat):
        return '—' if stat['mean'] is None else f"{stat['mean']:.3f} [{stat['min']:.3f}, {stat['max']:.3f}]"
    for row in report['summary']:
        pairs = '; '.join(f'{k}: {fmt(v)}' for k, v in row['binder_target_chainpair_iptm'].items()) or '—'
        lines.append(f"| {row['id']} | {row['source_native_filter']} | {row['completed']}/{row['expected']} | {fmt(row['binder_plddt_0_100'])} | {pairs} | {fmt(row['target_global_CA_RMSD_A'])} | {fmt(row['binder_target_atom_pairs_lt2A'])} | {fmt(row['binder_CA_RMSD_after_target_alignment_A'])} |")
    lines += ['', 'Detailed directional PAE, contact-local confidence, per-chain confidence, target-target scores, files, and missing outputs are in analysis.json.', '']
    lines += ['- ' + caveat for caveat in report['limitations']]
    (output / 'summary.md').write_text('\n'.join(lines) + '\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--prepared', required=True, type=Path)
    parser.add_argument('--output', required=True, type=Path)
    parser.add_argument('--evaluation-source', type=Path)
    args = parser.parse_args()
    report = analyze(args.prepared, args.evaluation_source)
    render(report, args.output)
    print(json.dumps({'analyzed': report['analyzed_predictions'], 'expected': report['expected_predictions']}))


if __name__ == '__main__':
    main()
